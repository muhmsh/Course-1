#include <iostream>
using namespace std;
int main()
{

    int price = 30;
    cout << "the price is : " << price << endl;
    cout << "the price after adding 15 is : "
         << price + 15 << endl;
    cout << "the price after adding  50 is : "
         << price + 50 << endl;
    price = 50;
    cout << "the new price is : " << price;

    return 0;
}